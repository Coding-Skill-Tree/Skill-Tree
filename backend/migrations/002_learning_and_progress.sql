CREATE TABLE skill_categories (
  id VARCHAR(64) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  sort_order INTEGER NOT NULL UNIQUE,
  active BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE skills (
  id VARCHAR(80) PRIMARY KEY,
  category_id VARCHAR(64) NOT NULL REFERENCES skill_categories(id) ON DELETE RESTRICT,
  title VARCHAR(120) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  learning_items JSONB NOT NULL DEFAULT '[]'::jsonb,
  position_x INTEGER NOT NULL DEFAULT 0,
  position_y INTEGER NOT NULL DEFAULT 0,
  catalog_version INTEGER NOT NULL DEFAULT 1,
  sort_order INTEGER NOT NULL DEFAULT 0,
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX skills_category_active_order_idx ON skills(category_id, active, sort_order);

CREATE TABLE skill_prerequisites (
  skill_id VARCHAR(80) NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,
  prerequisite_skill_id VARCHAR(80) NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (skill_id, prerequisite_skill_id),
  CONSTRAINT skill_prerequisites_no_self CHECK (skill_id <> prerequisite_skill_id)
);

CREATE TABLE questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  skill_id VARCHAR(80) NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,
  prompt TEXT NOT NULL,
  choices JSONB NOT NULL,
  correct_choice SMALLINT NOT NULL CHECK (correct_choice BETWEEN 0 AND 2),
  explanation TEXT NOT NULL DEFAULT '',
  active BOOLEAN NOT NULL DEFAULT true,
  is_demo BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT questions_choices_array CHECK (jsonb_typeof(choices) = 'array' AND jsonb_array_length(choices) = 3)
);
CREATE INDEX questions_skill_active_idx ON questions(skill_id, active);
CREATE UNIQUE INDEX questions_skill_prompt_unique ON questions(skill_id, prompt);

CREATE TABLE quiz_attempts (
  id UUID PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  skill_id VARCHAR(80) NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,
  catalog_version INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'completed', 'cancelled')),
  total_questions SMALLINT NOT NULL CHECK (total_questions > 0),
  correct_count SMALLINT CHECK (correct_count IS NULL OR correct_count BETWEEN 0 AND total_questions),
  passed BOOLEAN,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  UNIQUE (id, user_id)
);
CREATE INDEX quiz_attempts_user_history_idx ON quiz_attempts(user_id, started_at DESC, id DESC);
CREATE INDEX quiz_attempts_skill_open_idx ON quiz_attempts(user_id, skill_id, started_at DESC) WHERE status = 'in_progress';

CREATE TABLE quiz_attempt_questions (
  attempt_id UUID NOT NULL REFERENCES quiz_attempts(id) ON DELETE CASCADE,
  question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
  ordinal SMALLINT NOT NULL CHECK (ordinal > 0),
  prompt_snapshot TEXT NOT NULL,
  choices_snapshot JSONB NOT NULL,
  correct_choice_snapshot SMALLINT NOT NULL CHECK (correct_choice_snapshot BETWEEN 0 AND 2),
  explanation_snapshot TEXT NOT NULL DEFAULT '',
  selected_choice SMALLINT CHECK (selected_choice IS NULL OR selected_choice BETWEEN 0 AND 2),
  answered_at TIMESTAMPTZ,
  PRIMARY KEY (attempt_id, ordinal),
  UNIQUE (attempt_id, question_id)
);

CREATE TABLE completed_skills (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  skill_id VARCHAR(80) NOT NULL REFERENCES skills(id) ON DELETE RESTRICT,
  first_passed_attempt_id UUID NOT NULL REFERENCES quiz_attempts(id) ON DELETE RESTRICT,
  completed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, skill_id)
);

CREATE TABLE xp_outbox (
  event_id UUID PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  source_type VARCHAR(40) NOT NULL,
  source_id VARCHAR(128) NOT NULL,
  event_type VARCHAR(80) NOT NULL,
  amount INTEGER NOT NULL CHECK (amount > 0),
  payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'completed', 'failed')),
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  processed_at TIMESTAMPTZ,
  last_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (source_type, source_id, event_type)
);
CREATE INDEX xp_outbox_pending_idx ON xp_outbox(available_at, created_at) WHERE status IN ('pending', 'failed');

CREATE TABLE xp_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id UUID NOT NULL UNIQUE REFERENCES xp_outbox(event_id) ON DELETE RESTRICT,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  amount INTEGER NOT NULL CHECK (amount > 0),
  reason VARCHAR(80) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX xp_ledger_user_created_idx ON xp_ledger(user_id, created_at DESC, id DESC);

CREATE TABLE user_progress_revisions (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  revision BIGINT NOT NULL DEFAULT 0 CHECK (revision >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
