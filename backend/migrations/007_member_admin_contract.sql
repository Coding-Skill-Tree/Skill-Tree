ALTER TABLE member_profiles
  ADD COLUMN role VARCHAR(32) NOT NULL DEFAULT 'member',
  ADD COLUMN level SMALLINT NOT NULL DEFAULT 1,
  ADD CONSTRAINT member_profiles_role_nonempty CHECK (length(btrim(role)) > 0),
  ADD CONSTRAINT member_profiles_level_positive CHECK (level > 0);

CREATE TABLE member_auth_identities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  provider VARCHAR(32) NOT NULL CHECK (provider = 'google'),
  provider_subject VARCHAR(255) NOT NULL,
  email_at_link VARCHAR(254),
  linked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT member_auth_identities_subject_nonempty CHECK (length(btrim(provider_subject)) > 0),
  CONSTRAINT member_auth_identities_user_provider_unique UNIQUE (user_id, provider),
  CONSTRAINT member_auth_identities_provider_subject_unique UNIQUE (provider, provider_subject)
);

CREATE INDEX member_auth_identities_user_idx ON member_auth_identities(user_id);
